/**
 * Midnight ZK Simulation Module
 *
 * Simulates the Midnight blockchain's zero-knowledge proof system.
 *
 * Architecture mirrors real Midnight:
 *   • "Compact contracts" are TypeScript classes with prove() / verify() methods
 *   • Document commitments are BLAKE2b-256 hashes (real Midnight uses Pedersen commitments)
 *   • Proof objects include simulated Groth16 transcript (π_A, π_B, π_C points)
 *   • Verification is a deterministic hash check (real Midnight uses bilinear pairings)
 *   • Circuit-specific verification keys are derived from known constants
 *
 * The security model:
 *   • Cannot forge a valid proof without knowing the document fields
 *   • Verification requires no access to the original document
 *   • Nullifiers prevent proof replay across different claims
 */

import {
    blake2b256,
    blake2b256str,
    toBase64,
    fromBase64,
    toHex,
    concat,
    randomSalt,
    randomId,
} from './crypto';
import {
    type SchemaType,
    renderClaimDescription,
} from './schemas';
import {
    MIDNIGHT_CONTRACT_PREFIX,
    MIDNIGHT_NETWORK_VERSION,
} from './config';

// ── Proof data types ─────────────────────────────────────────────────────────

/** Simulated Groth16 proof points (each point is a 32-byte hex string) */
export interface Groth16Proof {
    /** Simulated G1 point π_A */
    a:    string;
    /** Simulated G2 point π_B (two field elements) */
    b:    [string, string];
    /** Simulated G1 point π_C */
    c:    string;
}

/** A complete Midnight ZK proof bundle — safe to share publicly */
export interface MidnightProof {
    /** Unique proof identifier (hex) */
    proofId:           string;
    /** Schema type (document category) */
    schemaType:        SchemaType;
    /**
     * Deployed Compact contract ID.
     * In production: derived from the Contract address on Midnight blockchain.
     */
    contractId:        string;
    /** Claim type identifier */
    claimType:         string;
    /** Public claim parameters (revealed to verifier) */
    claimParams:       Record<string, unknown>;
    /** Human-readable description of what was proven */
    claimDescription:  string;
    /** The verdict — true means the claim holds */
    satisfiesClaim:    boolean;
    /**
     * BLAKE2b-256 commitment to (fields | owner | salt).
     * Irreversibly binds this proof to a specific document instance.
     */
    documentCommitment: string;
    /**
     * Nullifier: BLAKE2b(commitment | claimType | claimParams_json).
     * Prevents re-use of the same proof for different claims.
     */
    nullifier:         string;
    /** Simulated Groth16 proof transcript */
    proof:             Groth16Proof;
    /**
     * Verification hash: binds proof points to public inputs.
     * verificationHash = BLAKE2b(π_A | π_C | satisfiesClaim | nullifier | vk)
     */
    verificationHash:  string;
    /**
     * Circuit-specific verification key (derived from circuit constants).
     * In production: generated by Midnight trusted setup ceremony.
     */
    vk:                string;
    /** Wallet address of the proof generator */
    ownerAddress:      string;
    /** Unix timestamp (ms) */
    timestamp:         number;
    /** Optional expiry (Unix ms). Null = never expires. */
    expiresAt:         number | null;
    /** Simulated Midnight transaction hash */
    midnightTxHash:    string;
    /** Network version tag */
    networkVersion:    string;
}

/** Result returned by verifyProof */
export interface VerificationResult {
    valid:            boolean;
    satisfiesClaim:   boolean;
    claimDescription: string;
    schemaType:       SchemaType;
    claimType:        string;
    claimParams:      Record<string, unknown>;
    ownerAddress:     string;
    timestamp:        number;
    proofId:          string;
    contractId:       string;
    /** Human-readable summary for the verifier UI */
    summary:          string;
    error?:           string;
}

